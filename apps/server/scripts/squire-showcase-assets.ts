#!/usr/bin/env node
// @effect-diagnostics nodeBuiltinImport:off
/**
 * Builds the showcase's shipped assets. The server ships as one bundle
 * (and one executable), so the template and the Lead stills travel as TS
 * modules, like the skill text. `template.html` stays the template's truth;
 * the stills live only in their module, and `stills/manifest.json` records
 * each one's hash, which `SquireShowcase.test.ts` checks the module against.
 *
 *   node apps/server/scripts/squire-showcase-assets.ts template
 *   node apps/server/scripts/squire-showcase-assets.ts stills <gold-stills-dir> [--tint gold] [--crest vector-overlay]
 *
 * Run `vp fmt` on the generated modules afterwards. `stills` needs `cwebp`
 * and `dwebp` (libwebp) on the host. Each still is
 * resized to the header's 2x size, the colour under alpha 0 is zeroed, it is
 * re-encoded lossless with `-exact` (lossy WebP cannot keep those zeros), and
 * decoded again to prove it: `stills/manifest.json` records the check.
 */
import * as NodeChildProcess from "node:child_process";
import * as NodeCrypto from "node:crypto";
import * as NodeFS from "node:fs";
import * as NodeOS from "node:os";
import * as NodePath from "node:path";

const showcaseDir = NodePath.resolve(import.meta.dirname, "../src/squire/showcase");
const stillsDir = NodePath.join(showcaseDir, "stills");
// The header shows the figure 160 px tall (the readability floor), so 2x density.
const WIDTH = 218;
const HEIGHT = 320;
const STILL_NAME =
  /^lead-(female|male)-(down|up)-(helmet|lance|astrolabe|grimoire|armillary|none)\.webp$/;

const run = (command: string, args: ReadonlyArray<string>) =>
  NodeChildProcess.execFileSync(command, args, { stdio: ["ignore", "ignore", "pipe"] });

const sha256 = (bytes: Uint8Array) => NodeCrypto.createHash("sha256").update(bytes).digest("hex");

/** PAM (`dwebp -pam`): a text header, then RGBA rows. */
const pamPixels = (pam: Buffer) => {
  const end = pam.indexOf("ENDHDR\n");
  if (end < 0 || !pam.subarray(0, end).toString("latin1").includes("TUPLTYPE RGB_ALPHA")) {
    throw new Error("expected an RGBA PAM");
  }
  return pam.subarray(end + "ENDHDR\n".length);
};

const zeroUnderAlpha = (pixels: Buffer) => {
  for (let index = 0; index < pixels.length; index += 4) {
    if (pixels[index + 3] === 0) pixels.fill(0, index, index + 3);
  }
};

const countUnderAlpha = (pixels: Buffer) => {
  let transparent = 0;
  let coloured = 0;
  for (let index = 0; index < pixels.length; index += 4) {
    if (pixels[index + 3] !== 0) continue;
    transparent += 1;
    if ((pixels[index]! | pixels[index + 1]! | pixels[index + 2]!) !== 0) coloured += 1;
  }
  return { transparent, coloured };
};

const flag = (args: ReadonlyArray<string>, name: string, fallback: string) => {
  const index = args.indexOf(name);
  return index >= 0 && args[index + 1] !== undefined ? args[index + 1]! : fallback;
};

const writeModule = (file: string, body: string) => {
  NodeFS.writeFileSync(
    file,
    `// Generated by apps/server/scripts/squire-showcase-assets.ts; do not edit.\n${body}`,
  );
};

const buildTemplate = () => {
  const html = NodeFS.readFileSync(NodePath.join(showcaseDir, "template.html"), "utf8");
  const version = /<meta name="squire-showcase-template" content="(\d+)"\s*\/?>/.exec(html)?.[1];
  if (version === undefined) throw new Error("template.html declares no version");
  writeModule(
    NodePath.join(showcaseDir, "template.generated.ts"),
    `export const SHOWCASE_TEMPLATE_VERSION = ${version};\nexport const SHOWCASE_TEMPLATE_HTML = ${JSON.stringify(html)};\n`,
  );
  process.stdout.write(`template v${version}: ${Buffer.byteLength(html)} bytes\n`);
};

const buildStills = (source: string, tint: string, crest: string) => {
  const names = NodeFS.readdirSync(source)
    .filter((name) => STILL_NAME.test(name))
    .toSorted();
  if (names.length !== 24)
    throw new Error(`expected 24 Lead stills in ${source}, found ${names.length}`);
  const work = NodeFS.mkdtempSync(NodePath.join(NodeOS.tmpdir(), "squire-stills-"));
  NodeFS.mkdirSync(stillsDir, { recursive: true });
  // Older runs kept a .webp copy beside the module; nothing reads one.
  for (const stale of NodeFS.readdirSync(stillsDir).filter((name) => name.endsWith(".webp"))) {
    NodeFS.rmSync(NodePath.join(stillsDir, stale));
  }
  const stills = names.map((name) => {
    const [, appearance, hood, equipment] = STILL_NAME.exec(name)!;
    const resized = NodePath.join(work, "resized.webp");
    const pam = NodePath.join(work, "still.pam");
    const out = NodePath.join(work, name);
    run("cwebp", [
      "-quiet",
      "-lossless",
      "-exact",
      "-resize",
      `${WIDTH}`,
      `${HEIGHT}`,
      NodePath.join(source, name),
      "-o",
      resized,
    ]);
    run("dwebp", ["-quiet", resized, "-pam", "-o", pam]);
    const raw = NodeFS.readFileSync(pam);
    zeroUnderAlpha(pamPixels(raw));
    NodeFS.writeFileSync(pam, raw);
    run("cwebp", ["-quiet", "-lossless", "-exact", "-z", "9", pam, "-o", out]);
    run("dwebp", ["-quiet", out, "-pam", "-o", pam]);
    const check = countUnderAlpha(pamPixels(NodeFS.readFileSync(pam)));
    if (check.coloured !== 0)
      throw new Error(`${name}: ${check.coloured} coloured pixels under alpha 0`);
    const bytes = NodeFS.readFileSync(out);
    return {
      key: `${appearance}-${hood}-${equipment}`,
      appearance,
      hood,
      equipment,
      file: name,
      bytes: bytes.byteLength,
      sha256: sha256(bytes),
      transparentPixels: check.transparent,
      colouredUnderAlpha0: check.coloured,
      base64: bytes.toString("base64"),
    };
  });
  NodeFS.rmSync(work, { recursive: true, force: true });
  const totalBytes = stills.reduce((sum, still) => sum + still.bytes, 0);
  const manifest = {
    tint,
    crest,
    width: WIDTH,
    height: HEIGHT,
    encoding: "webp lossless -exact; RGB zeroed under alpha 0, checked by decoding",
    source: NodePath.relative(NodePath.resolve(import.meta.dirname, "../../.."), source),
    totalBytes,
    stills: stills.map(({ base64: _base64, ...still }) => still),
  };
  NodeFS.writeFileSync(
    NodePath.join(stillsDir, "manifest.json"),
    `${JSON.stringify(manifest, null, 2)}\n`,
  );
  const entries = stills
    .map(
      (still) =>
        `  ${JSON.stringify(still.key)}: { sha256: ${JSON.stringify(still.sha256)}, base64: ${JSON.stringify(still.base64)} },`,
    )
    .join("\n");
  writeModule(
    NodePath.join(stillsDir, "stills.generated.ts"),
    `/** The Lead still set (manifest.json); swap tint or crest by regenerating, not in code. */\nexport const SHOWCASE_STILL_SET = {\n  tint: ${JSON.stringify(tint)},\n  crest: ${JSON.stringify(crest)},\n  width: ${WIDTH},\n  height: ${HEIGHT},\n  mimeType: "image/webp",\n} as const;\n\nexport const SHOWCASE_STILLS: Readonly<Record<string, { readonly sha256: string; readonly base64: string }>> = {\n${entries}\n};\n`,
  );
  process.stdout.write(
    `${stills.length} stills, ${totalBytes} bytes (${WIDTH}x${HEIGHT}), none coloured under alpha 0\n`,
  );
};

const [command, ...rest] = process.argv.slice(2);
if (command === "template") buildTemplate();
else if (command === "stills" && rest[0] !== undefined) {
  buildStills(
    NodePath.resolve(rest[0]),
    flag(rest, "--tint", "gold"),
    flag(rest, "--crest", "vector-overlay"),
  );
} else {
  process.stderr.write(
    "usage: squire-showcase-assets.ts template | stills <gold-stills-dir> [--tint t] [--crest c]\n",
  );
  process.exitCode = 1;
}
